"""Paper tables and figure from the executed notebook 4 (test split).

Reads the outputs that notebook 4 printed in its one run on the test split, so no score is computed again.
Writes, under report/overleaf-bln600/:
  tables/results.tex   main results table (span BERTScore and Fact Recovery Rate with 95% CIs)
  tables/format.tex    format failures per level and LLM scores over valid answers only
  figures/results_levels.pdf   the three primary scores by level, one line per main method, CIs as bands

Run: .venv/bin/python scripts/paper_results.py
"""
import json
import re
from html.parser import HTMLParser
from pathlib import Path

import matplotlib.pyplot as plt
import scienceplots  # noqa: F401  (registers the "science" matplotlib styles)

from blnrepair.plots import INK, MUTED

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "notebooks" / "04_evaluation.ipynb"
REPORT = ROOT / "report" / "overleaf-bln600"
LEVELS = ["1w", "10", "25", "50", "75"]
LEVEL_NAMES = {"1w": "1w", "10": "10\\%", "25": "25\\%", "50": "50\\%", "75": "75\\%"}
MAIN = ["BERT + dictionary", "few-shot", "dictionary lookup", "BART"]  # with intervals
PLAIN = ["no repair", "BERT, no dictionary", "few-shot + article"]  # point estimates only
HEAD = {"BERT + dictionary": "BERT+dict.", "few-shot": "LLM", "dictionary lookup": "Lookup", "BART": "BART",
        "no repair": "None", "BERT, no dictionary": "BERT", "few-shot + article": "LLM+art."}
# Okabe-Ito colours (colour-blind safe), plus one marker per method so identity never rests on colour alone
COLORS = {"BERT + dictionary": "#0072B2", "few-shot": "#D55E00", "dictionary lookup": "#E69F00", "BART": "#009E73"}
MARKERS = {"BERT + dictionary": "o", "few-shot": "s", "dictionary lookup": "^", "BART": "D"}


class TableParser(HTMLParser):
    """The first HTML table of a pandas display: header row and body rows as lists of cell texts."""

    def __init__(self):
        super().__init__()
        self.rows, self.cell = [], None

    def handle_starttag(self, tag, attrs):
        if tag == "tr":
            self.rows.append([])
        elif tag in ("td", "th"):
            self.cell = ""

    def handle_endtag(self, tag):
        if tag in ("td", "th") and self.cell is not None:
            self.rows[-1].append(self.cell.strip())
            self.cell = None

    def handle_data(self, data):
        if self.cell is not None:
            self.cell += data


def titled_tables():
    """Every table in notebook 4 that follows a printed title line, as {title: {level: {method: cell}}}."""
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    assert 'SPLIT = "test"' in "".join(nb["cells"][1]["source"]), "notebook 4 is not the test run"
    tables, title = {}, None
    for cell in nb["cells"]:
        for out in cell.get("outputs", []):
            if out.get("output_type") == "stream":
                lines = "".join(out["text"]).strip().splitlines()
                title = lines[-1].strip() if lines else title
            elif "text/html" in out.get("data", {}) and title:
                parser = TableParser()
                parser.feed("".join(out["data"]["text/html"]))
                header = parser.rows[0]
                body = [r for r in parser.rows[1:] if r and r[0] in LEVELS + ["all"]]
                tables[title] = {r[0]: dict(zip(header[1:], r[1:])) for r in body}
                title = None
    return tables, nb


CELL = re.compile(r"(-?\d+\.\d+) \[(-?\d+\.\d+), (-?\d+\.\d+)\]")


def parse_cell(text):
    m = CELL.fullmatch(text)
    return tuple(float(x) for x in m.groups()) if m else (float("nan"),) * 3


def short(x):
    """Two decimals without the leading zero, for the interval bounds."""
    return f"{x:.2f}".replace("0.", ".", 1).replace("-", "$-$")


def num(x):
    return f"{x:.2f}".replace("-", "$-$")


def results_table(tables):
    # anchor recovery is shown with its intervals in the figure (third panel), to keep the table short
    blocks = [("BERTScore span", "BERTScore (span)"), ("Fact Recovery Rate", "\\frr{}")]
    cols = MAIN + PLAIN
    lines = ["% Generated by scripts/paper_results.py from the executed notebooks/04_evaluation.ipynb (test split).",
             "\\begin{table*}[t]", "\\centering", "\\small\\setlength{\\tabcolsep}{4pt}",
             "\\begin{tabular}{l" + "c" * len(MAIN) + "c" + "|cc}", "\\toprule",
             " & \\multicolumn{4}{c}{Main methods (95\\% CI)} & Floor & \\multicolumn{2}{c}{Ablations} \\\\",
             "Level & " + " & ".join(HEAD[m] for m in cols) + " \\\\", "\\midrule"]
    for key, name in blocks:
        lines.append(f"\\multicolumn{{{len(cols) + 1}}}{{l}}{{\\textit{{{name}}}}} \\\\")
        table = tables[key]
        for lv in LEVELS:
            vals = [parse_cell(table[lv][m]) for m in cols]
            best = max(v[0] for v, m in zip(vals, cols) if m in MAIN)
            cells = []
            for (v, lo, hi), m in zip(vals, cols):
                point = num(v)
                if m in MAIN and v == best:
                    point = f"\\textbf{{{point}}}"
                cells.append(f"{point}\\,{{\\tiny[{short(lo)}, {short(hi)}]}}" if m in MAIN else point)
            lines.append(f"{LEVEL_NAMES[lv]} & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule" if key != blocks[-1][0] else "\\bottomrule")
    lines += ["\\end{tabular}",
              "\\caption{Test results, 150 sentences per level (95\\% bootstrap intervals over sentences). "
              "Best main method per row in bold. LLM = few-shot; a format failure counts as no repair "
              "(Table~\\ref{tab:format}); anchor recovery is in Figure~\\ref{fig:results}. BART is descriptive only; BERT without dictionary and LLM with the "
              "article are ablations.}",
              "\\label{tab:results}", "\\end{table*}"]
    return "\n".join(lines) + "\n"


def valid_only(nb):
    """LLM and BART scores over valid answers: {(level, method): (bertscore, frr, anchor, n)}."""
    text = next("".join(o["data"]["text/plain"]) for c in nb["cells"] for o in c.get("outputs", [])
                if "text/plain" in o.get("data", {}) and "BERTScore span" in "".join(o["data"]["text/plain"])
                and "size" in "".join(o["data"]["text/plain"]))
    out, level = {}, None
    for line in text.splitlines():
        m = re.match(r"^(1w|10|25|50|75)?\s+(few-shot \+ article|few-shot|BART)\s+([\d.]+)\s+(\d+)\s+([\d.]+)\s+\d+\s+([\d.]+)\s+\d+", line)
        if m:
            level = m.group(1) or level
            out[(level, m.group(2))] = (float(m.group(3)), float(m.group(5)), float(m.group(6)), int(m.group(4)))
    return out


def format_table(tables, nb):
    fails = next(t for t in tables.values() if "all" in t)  # the format-failure table has an "all" row
    valid = valid_only(nb)
    lines = ["% Generated by scripts/paper_results.py from the executed notebooks/04_evaluation.ipynb (test split).",
             "\\begin{table}[t]", "\\centering", "\\small\\setlength{\\tabcolsep}{3pt}",
             "\\begin{tabular}{lccc|ccc}", "\\toprule",
             " & \\multicolumn{3}{c|}{Format failures} & \\multicolumn{3}{c}{LLM, valid answers} \\\\",
             "Level & LLM & +art. & BART & BERTSc. & FRR & $n$ \\\\", "\\midrule"]
    for lv in LEVELS:  # the totals are given in the text
        f = [fails[lv][m] for m in ["few-shot", "few-shot + article", "BART"]]
        b, frr, _, n = valid[(lv, "few-shot")]
        lines.append(f"{LEVEL_NAMES[lv]} & " + " & ".join(f) + f" & {b:.2f} & {frr:.2f} & {n} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\caption{Format failures per level (of 150; all levels: "
              + ", ".join(fails["all"][m] for m in ["few-shot", "few-shot + article", "BART"])
              + ") and the LLM over its valid answers ($n$ rows; FRR = \\frr{}).}", "\\label{tab:format}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def figure(tables, valid):
    metrics = [("BERTScore span", "BERTScore (span)"), ("Fact Recovery Rate", "Fact Recovery Rate"),
               ("anchor recovery", "Anchor recovery")]
    plt.style.use(["science", "no-latex"])
    plt.rcParams.update({"font.family": "serif", "font.serif": ["Times", "Times New Roman", "DejaVu Serif"],
                         "font.size": 8, "axes.linewidth": 0.6, "pdf.fonttype": 42})
    fig, axes = plt.subplots(1, 3, figsize=(6.3, 1.75))
    x = range(len(LEVELS))
    for i, (ax, (key, title)) in enumerate(zip(axes, metrics)):
        table = tables[key]
        ref = [parse_cell(table[lv]["no repair"])[0] for lv in LEVELS]
        ax.plot(x, ref, color=MUTED, linewidth=1, linestyle="--", label="no repair")
        for m in MAIN:
            v, lo, hi = zip(*(parse_cell(table[lv][m]) for lv in LEVELS))
            ax.fill_between(x, lo, hi, color=COLORS[m], alpha=0.15, linewidth=0)
            ax.plot(x, v, color=COLORS[m], linewidth=1.3, marker=MARKERS[m], markersize=3.2, label=HEAD[m])
        ax.plot(x, [valid[(lv, "few-shot")][i] for lv in LEVELS], color=COLORS["few-shot"], linewidth=1,
                linestyle=":", label="LLM, valid answers")
        ax.set_xticks(list(x), ["1w", "10%", "25%", "50%", "75%"])
        ax.minorticks_off()
        ax.tick_params(top=False, right=False)
        ax.set_title(title, fontsize=8.5, color=INK, loc="left")
        ax.yaxis.grid(True, color="#dddddd", linewidth=0.5)
        ax.set_axisbelow(True)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
    axes[0].set_ylim(-0.4, 1.0)
    for ax in axes[1:]:
        ax.set_ylim(0, 0.75)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=6, frameon=False, bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=(0, 0.1, 1, 1), w_pad=1.2)
    return fig


def main():
    tables, nb = titled_tables()
    (REPORT / "tables").mkdir(exist_ok=True)
    (REPORT / "tables" / "results.tex").write_text(results_table(tables), encoding="utf-8")
    (REPORT / "tables" / "format.tex").write_text(format_table(tables, nb), encoding="utf-8")
    figure(tables, valid_only(nb)).savefig(REPORT / "figures" / "results_levels.pdf", bbox_inches="tight")
    print("written: tables/results.tex, tables/format.tex, figures/results_levels.pdf")


if __name__ == "__main__":
    main()
